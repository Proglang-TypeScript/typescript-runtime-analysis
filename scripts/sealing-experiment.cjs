const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const {trace} = require('../packages/runtime-tracer/index.cjs');
const {synthesize} = require('../packages/relational-signatures/index.cjs');
const {propose, challenge, refine} = require('../packages/sealing/proposals.cjs');
const {trial} = require('../packages/sealing/trials.cjs');
const {checkClient} = require('./relational-experiment.cjs');
const fixture = path.resolve(__dirname, '../experiments/sealing');
const save = (directory, name, value) => fs.writeFileSync(path.join(directory, name), JSON.stringify(value, null, 2) + '\n');
function aggregate(directory) {
  const data = JSON.parse(fs.readFileSync(path.join(directory, 'evaluation.json'), 'utf8'));
  const lines = ['configuration,valid_client_pass,invalid_client_rejected,valid_errors,invalid_errors'];
  for (const row of data.clients) lines.push(`${row.configuration},${Number(row.valid.pass)},${Number(!row.invalid.pass)},${row.valid.diagnostics.length},${row.invalid.diagnostics.length}`);
  fs.writeFileSync(path.join(directory, 'tables.csv'), lines.join('\n') + '\n');
  const trials = ['function,candidate,passed,violations,inconclusive,exceptions,timeouts,harness_failures'];
  for (const row of data.validation) trials.push(`${row.candidate.functionName},${row.candidate.kind},${['passed', 'seal-violation', 'inconclusive', 'exception', 'timeout', 'harness-failure'].map(status => row.trials.filter(trial => trial.result.status === status).length).join(',')}`);
  fs.writeFileSync(path.join(directory, 'trials.csv'), trials.join('\n') + '\n');
}
function experiment({directory = path.resolve(__dirname, '../experiments/results/sealing')} = {}) {
  fs.mkdirSync(directory, {recursive: true});
  const output = path.join(directory, 'proposing.trace.json');
  trace(path.join(fixture, 'inference.js'), {targetRoot: fixture, output, package: 'tra-sealing-fixture', version: '1.0.0', publicModule: 'module', evidence: 'fixture', trustedFixture: true, captureInvocations: true});
  const proposing = JSON.parse(fs.readFileSync(output + '.invocations.json', 'utf8'));
  const candidates = propose(proposing);
  save(directory, 'proposals.json', candidates);
  assert.deepEqual(candidates.map(row => row.functionName).sort(), ['identity', 'nonParametric', 'tagIdentity']);
  const validation = candidates.map(candidate => challenge(path.join(fixture, 'module.js'), candidate, {trustedFixture: true}));
  assert.equal(validation.find(row => row.candidate.functionName === 'identity').verdict, 'validated-on-supported-trials');
  assert.equal(validation.find(row => row.candidate.functionName === 'nonParametric').verdict, 'rejected');
  const refinements = validation.map(row => refine(row));
  const constrained = refinements.find(row => row.decision === 'constraint');
  assert.ok(constrained);
  const constraintValidation = challenge(path.join(fixture, 'module.js'), constrained.candidate, {trustedFixture: true});
  assert.equal(constraintValidation.verdict, 'validated-on-supported-trials');
  validation.push(constraintValidation);
  save(directory, 'sealed-trials.json', validation);
  save(directory, 'refinements.json', refinements);
  const variable = {kind: 'variable', name: 'T'};
  const contract = {variables: {T: null}, parameters: [variable], result: variable};
  const callbackContract = {...contract, parameters: [variable, {kind: 'function', parameters: [variable], result: variable}]};
  const callback = trial(path.join(fixture, 'module.js'), 'callbackIdentity', {contract: callbackContract, bindings: {T: 'number'}, inputs: [{family: 'number', value: 7}, {family: 'callback', operation: 'identity'}]}, {trustedFixture: true});
  assert.equal(callback.status, 'passed');
  save(directory, 'callback-polarity.json', callback);
  const unsupported = ['primitiveBranch', 'coerce', 'equal', 'native', 'serialize', 'objectIdentity', 'reflect'].map(name => ({functionName: name, result: trial(path.join(fixture, 'module.js'), name, {contract, bindings: {T: 'number'}, inputs: [{family: 'number', value: 7}]}, {trustedFixture: true})}));
  assert.ok(unsupported.every(row => row.result.status === 'inconclusive'));
  save(directory, 'unsupported-interactions.json', unsupported);
  const passive = synthesize([proposing]);
  const declarations = {};
  for (const kind of ['component-union', 'observation-overloads']) declarations[kind] = passive.filter(row => candidates.some(candidate => candidate.functionName === row.functionName)).map(row => row.candidates.find(candidate => candidate.kind === kind)?.text || '').join('\n');
  declarations['passive-relational'] = candidates.map(row => row.text).join('\n');
  declarations['sealing-refinement'] = refinements.map(row => row.decision === 'overloads' ? row.text : row.candidate.text).join('\n');
  const valid = fs.readFileSync(path.join(fixture, 'held-out-valid.ts'), 'utf8');
  const invalid = fs.readFileSync(path.join(fixture, 'held-out-invalid.ts'), 'utf8');
  const clients = Object.entries(declarations).map(([configuration, text]) => {
    fs.writeFileSync(path.join(directory, configuration + '.d.ts'), text);
    assert.equal(checkClient(text, "import * as api from './module';\n").pass, true);
    return {configuration, valid: checkClient(text, valid, {native: configuration === 'sealing-refinement'}), invalid: checkClient(text, invalid)};
  });
  const sealing = clients.find(row => row.configuration === 'sealing-refinement');
  assert.equal(sealing.valid.pass, true, JSON.stringify(sealing.valid));
  assert.equal(sealing.valid.native.exit, 0, sealing.valid.native.diagnostics);
  assert.equal(sealing.invalid.pass, false);
  assert.equal(clients.find(row => row.configuration === 'passive-relational').invalid.pass, true);
  const constraintInvalid = checkClient(declarations['sealing-refinement'], fs.readFileSync(path.join(fixture, 'constraint-invalid.ts'), 'utf8'));
  assert.equal(constraintInvalid.pass, false);
  const evaluation = {purpose: 'Known first-party synthetic fixtures; not publication evaluation or universal soundness', clients, constraintInvalid, validation, callback, unsupported, refinementDecisions: refinements, heldOutUsedForProposalOrRefinement: false};
  save(directory, 'evaluation.json', evaluation);
  save(directory, 'metadata.json', {node: process.version, compiler: require('typescript').version, nativeCompiler: '7.0.2', seed: 0, limits: {trialTimeoutMs: 3000, workerHeapMb: 128, maxInvocations: 128}, sourceHashes: Object.fromEntries(['module.js', 'inference.js', 'held-out-valid.ts', 'held-out-invalid.ts', 'constraint-invalid.ts'].map(file => [file, crypto.createHash('sha256').update(fs.readFileSync(path.join(fixture, file))).digest('hex')])), supportScope: 'Opaque first-order transport and shallow readonly string-field constraint; observability preflight conservative', heldOutPolicy: 'Only proposing observations/sealed challenges drive refinement; typing clients evaluation-only'});
  aggregate(directory);
  return {clients: clients.map(row => ({configuration: row.configuration, validPass: row.valid.pass, invalidRejected: !row.invalid.pass})), trials: validation.map(row => ({name: row.candidate.functionName, kind: row.candidate.kind, verdict: row.verdict})), callback: callback.status, unsupported: unsupported.length};
}
if (require.main === module) console.log(JSON.stringify(experiment(), null, 2));
module.exports = {experiment, aggregate};
